/**
 * دالة تطبيع نصوص البحث لتجاوز فروق الهمزات والتاء المربوطة والألف اللينة والمسافات
 */
export function normalizeArabicText(text: string): string {
  if (!text) return '';
  return text
    .trim()
    .toLowerCase()
    .replace(/[أإآ]/g, 'ا')
    .replace(/ة/g, 'ه')
    .replace(/ى/g, 'ي')
    .replace(/[ًٌٍَُِّْـ]/g, '')
    .replace(/["'״`\.\,\-\_]/g, ' ')
    .replace(/\s+/g, ' ');
}

/**
 * البحث عن بيانات مدير بواسطة الاسم
 */
export function findPrincipalByName(name: string): PrincipalRecord | undefined {
  if (!name) return undefined;
  const clean = normalizeArabicText(name);
  return OFFICIAL_PRINCIPALS_RECORDS.find((p) => {
    const pClean = normalizeArabicText(p.name);
    return pClean === clean || pClean.includes(clean) || clean.includes(pClean);
  });
}

/**
 * البحث عن بيانات المدير المسؤول عن مدرسة معينة
 */
export function findPrincipalBySchoolName(schoolName: string): PrincipalRecord | undefined {
  if (!schoolName) return undefined;
  const clean = normalizeArabicText(schoolName);

  // 1. بحث بالمطابقة المباشرة للاسم القياسي
  const direct = OFFICIAL_PRINCIPALS_RECORDS.find((p) => {
    const sClean = normalizeArabicText(p.schoolName);
    return sClean === clean || sClean.includes(clean) || clean.includes(sClean);
  });
  if (direct) return direct;

  // 2. بحث باسم المدرسة المختصر في وثيقة المديرية
  return OFFICIAL_PRINCIPALS_RECORDS.find((p) => {
    const docClean = normalizeArabicText(p.docSchoolName);
    return docClean === clean || docClean.includes(clean) || clean.includes(docClean);
  });
}
